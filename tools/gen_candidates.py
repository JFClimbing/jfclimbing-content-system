def cid(source, title, url=None):
    n = title.strip().lower().replace(" ", "")
    p = url.split("?")[0].rstrip("/") if url else ""
    raw = source.split(":")[0] + "|" + n + "|" + p
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:12]


